"""Application icon and per-platform app registration.

The tray can already draw its own icon at runtime, but a real installed
application needs artwork on disk and a launcher the OS can find. The
artwork is shipped inside the package (``assets/``) so registration needs
no build tools at install time; only Pillow is used, and only to resize.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

from . import paths

APP_NAME = "vpncli"
BUNDLE_ID = "com.github.sushantadhkr.vpncli"
VERSION = "1.0.1"

ASSETS_DIR = Path(__file__).resolve().parent / "assets"

#: Sizes Linux desktop entries expect in the hicolor theme.
LINUX_SIZES = (16, 24, 32, 48, 64, 128, 256, 512)

#: User applications first: it needs no administrator rights and Launch
#: Services indexes it just the same.
MACOS_APPLICATIONS = (
    Path.home() / "Applications",
    Path("/Applications"),
)
LINUX_ICONS = Path.home() / ".local" / "share" / "icons" / "hicolor"  # theme root
LINUX_APPLICATIONS = Path.home() / ".local" / "share" / "applications"
WINDOWS_START_MENU = Path(os.environ.get("APPDATA") or "") / "Microsoft" / "Windows" / "Start Menu" / "Programs"


class RegisterError(Exception):
    pass


# --------------------------------------------------------------------------
# artwork


def asset(name: str) -> Optional[Path]:
    path = ASSETS_DIR / name
    return path if path.is_file() else None


def icon_png() -> Optional[Path]:
    return asset("icon.png")


def icon_ico() -> Optional[Path]:
    return asset("vpncli.ico")


def icon_icns() -> Optional[Path]:
    return asset("vpncli.icns")


def has_artwork() -> bool:
    return icon_png() is not None


def _stamp_file() -> Path:
    return paths.data_dir() / "registered.json"


def read_stamp() -> Dict[str, object]:
    try:
        data = json.loads(_stamp_file().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def write_stamp() -> None:
    paths.ensure_data_dirs()
    paths.write_private(
        _stamp_file(),
        json.dumps({"platform": sys.platform, "version": VERSION, "python": sys.executable}),
    )


def is_registered() -> bool:
    """True only if the current version *and* interpreter are already registered.

    The launcher stores the absolute path of the Python that runs vpncli, so
    reinstalling into a different virtual environment has to rewrite it.
    """
    stamp = read_stamp()
    return stamp.get("version") == VERSION and stamp.get("python") == sys.executable


# --------------------------------------------------------------------------
# macOS


def _macos_target() -> Optional[Path]:
    for candidate in MACOS_APPLICATIONS:
        if os.access(str(candidate), os.W_OK):
            return candidate / ("%s.app" % APP_NAME)
    return None


def macos_launcher_text() -> str:
    """The bundle's launcher script.

    ``VPNCLI_TRAY_LAUNCHED`` is what stops the child from handing the tray
    back to this same bundle. It has to be written on every hand-over, not
    once: a launcher left behind by an older version would start a child
    that hands over again, and the tray would exit without ever running.
    """
    return (
        "#!/bin/sh\n"
        "# Launcher generated by vpncli register. Edit the app through vpncli.\n"
        "VPNCLI_TRAY_LAUNCHED=1 exec \"%s\" -m %s tray\n" % (sys.executable, APP_NAME)
    )


def install_macos() -> Optional[Path]:
    target = _macos_target()
    icns = icon_icns()
    if target is None:
        return None
    contents = target / "Contents"
    macos = contents / "MacOS"
    resources = contents / "Resources"
    for directory in (macos, resources):
        directory.mkdir(parents=True, exist_ok=True)

    launcher = macos / ("%s-tray" % APP_NAME)
    current = None
    try:
        current = launcher.read_text(encoding="utf-8", errors="replace")
    except OSError:
        pass
    if current != macos_launcher_text():
        launcher.write_text(macos_launcher_text(), encoding="utf-8")
        launcher.chmod(0o755)
    if icns is not None:
        shutil.copy2(str(icns), str(resources / ("%s.icns" % APP_NAME)))

    (contents / "PkgInfo").write_text("APPL????", encoding="utf-8")
    (contents / "Info.plist").write_text(_macos_plist(), encoding="utf-8")
    return target


def _macos_plist() -> str:
    values = (
        ("CFBundleName", APP_NAME),
        ("CFBundleDisplayName", "vpncli tray"),
        ("CFBundleIdentifier", BUNDLE_ID),
        ("CFBundleExecutable", "%s-tray" % APP_NAME),
        ("CFBundleIconFile", APP_NAME),
        ("CFBundleInfoDictionaryVersion", "6.0"),
        ("CFBundlePackageType", "APPL"),
        ("CFBundleShortVersionString", VERSION),
        ("CFBundleVersion", VERSION),
        # Menu bar only: no Dock icon, no application window.
        ("LSUIElement", "<true/>"),
        ("NSHighResolutionCapable", "<true/>"),
    )
    body = "\n".join(
        "\t<key>%s</key>\n\t%s" % (key, value if value.startswith("<") else "<string>%s</string>" % value)
        for key, value in values
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
        '<plist version="1.0">\n<dict>\n%s\n</dict>\n</plist>\n' % body
    )


# --------------------------------------------------------------------------
# Linux


def install_linux() -> Optional[Path]:
    png = icon_png()
    if png is None:
        return None
    theme = LINUX_ICONS
    created: List[Path] = []
    for size in LINUX_SIZES:
        folder = theme / ("%dx%d" % (size, size)) / "apps"
        folder.mkdir(parents=True, exist_ok=True)
        target = folder / ("%s.png" % APP_NAME)
        shutil.copy2(str(png), str(target))
        created.append(target)
    LINUX_APPLICATIONS.mkdir(parents=True, exist_ok=True)
    entry = LINUX_APPLICATIONS / ("%s-tray.desktop" % APP_NAME)
    entry.write_text(_linux_desktop(), encoding="utf-8")
    entry.chmod(0o755)
    _refresh_desktop_database()
    return entry


def _linux_desktop() -> str:
    return (
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Version=1.0\n"
        "Name=vpncli tray\n"
        "GenericName=OpenVPN client\n"
        "Comment=OpenVPN status in the system tray\n"
        "Exec=%s -m %s tray\n" % (sys.executable, APP_NAME)
        + "Icon=%s\n" % APP_NAME
        + "Terminal=false\n"
        "Categories=Network;Utility;\n"
        "Keywords=VPN;OpenVPN;proxy;tunnel;\n"
        "StartupNotify=false\n"
        "X-GNOME-UsesNotifications=true\n"
    )


def _refresh_desktop_database() -> None:
    for tool in ("update-desktop-database", "xdg-desktop-menu"):
        binary = shutil.which(tool)
        if binary is None:
            continue
        try:
            if os.path.basename(tool) == "update-desktop-database":
                subprocess.run(
                    [binary, str(LINUX_APPLICATIONS)],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
            else:
                subprocess.run(
                    [binary, "refresh"],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
            return
        except OSError:
            continue


# --------------------------------------------------------------------------
# Windows


def windows_target() -> Tuple[str, str]:
    """The command that starts the tray without a console window.

    ``gui-scripts`` already builds ``vpncli-tray.exe`` with the GUI
    subsystem, so using it shows vpncli's own icon and no black terminal.
    ``pythonw.exe`` is the fallback; plain ``python.exe`` would flash a
    console window, which is exactly what a menu bar app must not do.
    """
    folder = Path(sys.executable).parent
    launcher = folder / ("%s-tray.exe" % APP_NAME)
    if launcher.is_file():
        return str(launcher), ""
    windowless = folder / "pythonw.exe"
    if windowless.is_file():
        return str(windowless), "-m %s tray" % APP_NAME
    return sys.executable, "-m %s tray" % APP_NAME


def install_windows() -> Optional[Path]:
    if not paths.WINDOWS:
        return None
    ico = icon_ico()
    png = icon_png()
    folder = paths.data_dir() / "icons"
    folder.mkdir(parents=True, exist_ok=True)
    icon_target = folder / ("%s.ico" % APP_NAME)
    if ico is not None:
        shutil.copy2(str(ico), str(icon_target))
    elif png is not None:
        shutil.copy2(str(png), str(icon_target))
    else:
        return None
    WINDOWS_START_MENU.mkdir(parents=True, exist_ok=True)
    shortcut = WINDOWS_START_MENU / ("%s tray.lnk" % APP_NAME)
    target, arguments = windows_target()
    script = (
        "$s = (New-Object -ComObject WScript.Shell).CreateShortcut('%s');"
        "$s.TargetPath = '%s';"
        "$s.Arguments = '%s';"
        "$s.WorkingDirectory = '%s';"
        "$s.IconLocation = '%s,0';"
        "$s.Description = 'OpenVPN status in the system tray';"
        "$s.Save()" % (
            str(shortcut),
            target,
            arguments,
            str(paths.data_dir()),
            str(icon_target),
        )
    )
    try:
        subprocess.run(
            ["powershell", "-NoProfile", "-NonInteractive", "-Command", script],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return shortcut


# --------------------------------------------------------------------------
# entry point


def register(force: bool = False) -> Optional[Path]:
    """Install the app icon and launcher for the current platform.

    Safe to call on every start: it does nothing once the current version
    has been registered. Returns the launcher that was created, if any.
    """
    if not force and is_registered():
        return None
    if sys.platform == "darwin":
        created = install_macos()
    elif sys.platform.startswith("win"):
        created = install_windows()
    else:
        created = install_linux()
    write_stamp()
    return created


def macos_app() -> Optional[Path]:
    """The registered ``vpncli.app`` bundle, if it is usable.

    The launcher must exist and still point at an interpreter, otherwise
    handing the tray over to it would start nothing at all.
    """
    if sys.platform != "darwin":
        return None
    for folder in MACOS_APPLICATIONS:
        bundle = folder / ("%s.app" % APP_NAME)
        launcher = bundle / "Contents" / "MacOS" / ("%s-tray" % APP_NAME)
        if not bundle.is_dir():
            continue
        try:
            if not os.access(str(launcher), os.X_OK):
                continue
            script = launcher.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        quoted = re.findall(r'"([^"]+)"', script)
        if not any(Path(candidate).exists() for candidate in quoted):
            continue
        return bundle
    return None


def launch_macos_app() -> bool:
    """Start the tray through the app bundle, so macOS shows vpncli.

    Running the tray straight from Python leaves the process named
    "Python" everywhere and gives the status item no proper bundle to
    belong to. The bundle is a menu bar only app (LSUIElement), so
    launching it does not steal focus.

    The bundle is rewritten first. If its launcher were left over from an
    older version it would start a child that hands over all over again,
    and the tray would exit immediately without ever running.
    """
    try:
        install_macos()
    except OSError:
        pass
    bundle = macos_app()
    if bundle is None:
        return False
    try:
        subprocess.Popen(
            ["/usr/bin/open", "-g", "-a", str(bundle)],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except OSError:
        return False
    return True


def launcher_command() -> List[str]:
    return [sys.executable, "-m", APP_NAME, "tray"]